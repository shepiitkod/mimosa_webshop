function applyProductI18n(lang) {
  document.querySelectorAll("[data-product-i18n]").forEach((element) => {
    const raw = element.getAttribute("data-product-i18n");
    if (!raw) {
      return;
    }

    let data;
    try {
      data = JSON.parse(raw);
    } catch (error) {
      return;
    }

    const field = element.getAttribute("data-i18n-field");
    if (!field || !data[lang] || data[lang][field] === undefined) {
      return;
    }

    const value = data[lang][field];
    if (element.hasAttribute("data-i18n-html")) {
      element.innerHTML = value;
    } else {
      element.textContent = value;
    }
  });

  document.querySelectorAll("meta[name='description']").forEach((meta) => {
    const productDescription = document.querySelector(
      ".product-description[data-product-i18n][data-i18n-field='description']",
    );
    if (!productDescription) {
      return;
    }

    const raw = productDescription.getAttribute("data-product-i18n");
    if (!raw) {
      return;
    }

    try {
      const data = JSON.parse(raw);
      if (data[lang] && data[lang].description) {
        meta.setAttribute(
          "content",
          data[lang].description.replace(/<[^>]+>/g, " ").slice(0, 155),
        );
      }
    } catch (error) {
      /* ignore malformed product i18n payloads */
    }
  });
}

function switchLanguage(lang, remember) {
  if (remember !== false) {
    try {
      localStorage.setItem("selectedLanguage", lang);
    } catch (error) {
      /* storage blocked */
    }
  }
  document.documentElement.lang = lang;

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.remove("active");
    if (btn.getAttribute("data-lang") === lang) {
      btn.classList.add("active");
    }
  });

  document.querySelectorAll("[data-translate]").forEach((element) => {
    const key = element.getAttribute("data-translate");
    if (translations[lang] && translations[lang][key]) {
      let value = translations[lang][key];
      const count = element.getAttribute("data-count");
      if (count !== null && value.includes("{count}")) {
        value = value.replace("{count}", count);
      }
      // Only touch the DOM when the text really changes (keeps the first
      // paint stable and avoids needless layout).
      if (element.textContent !== value) element.textContent = value;
    }
  });

  document.querySelectorAll("[data-translate-html]").forEach((element) => {
    const key = element.getAttribute("data-translate-html");
    if (translations[lang] && translations[lang][key]) {
      const value = translations[lang][key];
      if (element.innerHTML !== value) element.innerHTML = value;
    }
  });

  document.querySelectorAll("[data-placeholder]").forEach((element) => {
    const key = element.getAttribute("data-placeholder");
    if (translations[lang] && translations[lang][key]) {
      element.setAttribute("placeholder", translations[lang][key]);
    }
  });

  applyProductI18n(lang);
  updateCompactLanguageUI();
  // Lets animations re-prepare text that translation just replaced.
  document.dispatchEvent(new CustomEvent("mimosa:lang", { detail: { lang } }));
}

function updateCompactLanguageUI() {
  document
    .querySelectorAll(".language-switcher")
    .forEach((languageSwitcher) => {
      const langCurrentBtn = languageSwitcher.querySelector(".lang-current");
      const activeBtn =
        languageSwitcher.querySelector(".lang-btn.active") ||
        languageSwitcher.querySelector(".lang-btn");

      if (!langCurrentBtn || !activeBtn) {
        return;
      }

      langCurrentBtn.textContent = activeBtn.textContent.trim();
    });
}

document.addEventListener("DOMContentLoaded", function () {
  // Saved choice first, otherwise the language picked in <head> from the
  // browser (fr / ua / ru, English for everyone else).
  let savedLang = null;
  try {
    savedLang = localStorage.getItem("selectedLanguage");
  } catch (error) {
    /* storage blocked */
  }
  savedLang = savedLang || document.documentElement.getAttribute("data-lang") || "en";
  switchLanguage(savedLang, false);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", function () {
      const lang = this.getAttribute("data-lang");
      switchLanguage(lang);

      document
        .querySelectorAll(".language-switcher")
        .forEach((languageSwitcher) => {
          const langCurrentBtn =
            languageSwitcher.querySelector(".lang-current");
          languageSwitcher.classList.remove("expanded");
          if (langCurrentBtn) {
            langCurrentBtn.setAttribute("aria-expanded", "false");
          }
        });
    });
  });

  document
    .querySelectorAll(".language-switcher")
    .forEach((languageSwitcher) => {
      const langCurrentBtn = languageSwitcher.querySelector(".lang-current");

      if (!langCurrentBtn) {
        return;
      }

      langCurrentBtn.addEventListener("click", function (event) {
        event.stopPropagation();
        const isExpanded = languageSwitcher.classList.toggle("expanded");
        langCurrentBtn.setAttribute("aria-expanded", String(isExpanded));
      });

      languageSwitcher.querySelectorAll(".lang-btn").forEach((btn) => {
        btn.addEventListener("click", function () {
          languageSwitcher.classList.remove("expanded");
          langCurrentBtn.setAttribute("aria-expanded", "false");
        });
      });
    });

  document.addEventListener("click", function (event) {
    document
      .querySelectorAll(".language-switcher.expanded")
      .forEach((languageSwitcher) => {
        if (languageSwitcher.contains(event.target)) {
          return;
        }

        languageSwitcher.classList.remove("expanded");

        const langCurrentBtn = languageSwitcher.querySelector(".lang-current");
        if (langCurrentBtn) {
          langCurrentBtn.setAttribute("aria-expanded", "false");
        }
      });
  });

  document.addEventListener("keydown", function (event) {
    if (event.key !== "Escape") {
      return;
    }

    document
      .querySelectorAll(".language-switcher.expanded")
      .forEach((languageSwitcher) => {
        languageSwitcher.classList.remove("expanded");

        const langCurrentBtn = languageSwitcher.querySelector(".lang-current");
        if (langCurrentBtn) {
          langCurrentBtn.setAttribute("aria-expanded", "false");
        }
      });
  });
});
